"""Cycle 13: fresh replication split test9 (10000-10019) and the c13a training seeds (28, 29)."""
import importlib.util
import json
import os

import pytest

from tuning.legacy import orig_baselines as OB
from tuning.legacy import run_legacy as RL

TEST3 = set(range(4000, 4020))          # c7_oracles.TEST3_SEEDS (not in RL.SPLITS)
C13_TRAIN_SEEDS = {28, 29}
LAB = os.path.expanduser("~/qrl-lab/.lab/tuning")
MAKE_C13 = os.path.join(LAB, "make_c13.py")


def _load(path, name):
    spec = importlib.util.spec_from_file_location(name, path)
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    return m


def test_test9_split_fresh_and_disjoint():
    assert RL.SPLITS["test9"] == tuple(range(10000, 10020)) == RL.TEST9_SEEDS
    for k, v in RL.SPLITS.items():
        if k != "test9":
            assert not set(RL.SPLITS["test9"]) & set(v), k
    assert not set(RL.SPLITS["test9"]) & TEST3
    assert all(s in RL.SEED_RANGE for s in RL.TEST9_SEEDS)
    assert RL.parse_splits("val,test9") == ("val", "test9")


def test_c13_training_seeds_outside_all_splits():
    every = set().union(*(set(v) for v in RL.SPLITS.values())) | TEST3
    assert not C13_TRAIN_SEEDS & every
    for s in C13_TRAIN_SEEDS:
        RL.check_seeds(s, "fair", ("val", "test9"))
    with pytest.raises(SystemExit):
        RL.check_seeds(10007, "fair", ("val", "test9"))


def test_baselines_report_test9(monkeypatch, tmp_path):
    monkeypatch.setitem(RL.SPLITS, "val", (1100,))
    monkeypatch.setitem(RL.SPLITS, "test9", (10000,))
    out = tmp_path / "b.json"
    res = OB.main(["--orig-variant", "spike300_d5", "--report-splits", "test9", "--ticks", "40", "--out", str(out)])
    assert "test9" in res and json.load(open(out))["test9_seeds"] == [10000]


@pytest.mark.skipif(not os.path.exists(MAKE_C13), reason="lab generator not present")
def test_lab_generators_exclude_test9():
    every = set().union(*(set(v) for v in RL.SPLITS.values())) | TEST3
    for name in ("make_c12", "make_c13"):
        assert set(_load(os.path.join(LAB, f"{name}.py"), name).EVAL_SEEDS) == every, name
    for name in ("make_c10b", "make_c11a"):
        assert set(range(10000, 10020)) <= _load(os.path.join(LAB, f"{name}.py"), name).EVAL_SEEDS, name
    s = _load(os.path.join(LAB, "sum_c10.py"), "sum_c10")
    assert s.SPLIT_SEEDS["test9"] == list(RL.TEST9_SEEDS)


@pytest.mark.skipif(not os.path.exists(MAKE_C13), reason="lab generator not present")
def test_make_c13_entries():
    m = _load(MAKE_C13, "make_c13")
    ents, cpu = m.build([28, 29])
    assert len(ents) == 2 * 5 + 1 and len({e["name"] for e in ents}) == len(ents)
    assert not m.collisions(ents)
    for e in ents:
        c = e["cmd"]
        assert e["name"].startswith("c13a-") and c[c.index("--out") + 1].startswith("tuning/results/c13a/")
        if "--eval-split" in c:
            assert RL.parse_splits(c[c.index("--eval-split") + 1]) == ("val", "test9")
            assert c[c.index("--orig-variant") + 1] == "spike300_d5" and e["seed"] in (28, 29)
        else:
            assert c[c.index("--report-splits") + 1] == "test9"
    # same arms and schedules as c12a on spike300_d5: commands equal after substituting tag, seed and split
    c12 = _load(os.path.join(LAB, "make_c12.py"), "make_c12")
    ref, _ = c12.build("a", [28, 29])

    def norm(e, tag, split):
        return json.dumps(e).replace(tag, "TAG").replace(split, "SPLIT")
    ref = {norm(e, "c12a", "test8") for e in ref if "spike300_d5" in json.dumps(e)}
    assert {norm(e, "c13a", "test9") for e in ents} == ref
    # larger version (cycle 13 B) generated by flags only
    big, _ = m.build([30, 31, 32], ("spike300_d5", "spike300_d10"), "c13b")
    assert len(big) == 2 * 3 * 5 + 2 and all(e["name"].startswith("c13b-") for e in big)
