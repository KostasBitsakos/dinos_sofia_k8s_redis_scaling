#!/usr/bin/env python3
"""Reward-variant prototype evaluation (dev seeds 1000-1004 only, deterministic baseline replays, no training).
Variants (reward_dinos.json 'variants'): default (p95, served-U), V1 (mean-latency D), V2 (V1 + offered-demand U),
V3 (p95 D + offered-demand U). Writes reward_variants_report.md next to this file."""
import json
import multiprocessing as mp
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
os.environ.setdefault("OMP_NUM_THREADS", "1")
import adapter  # noqa: E402,F401
import numpy as np  # noqa: E402
from env import SimV2, load_reward_dinos  # noqa: E402
from params import SimParams  # noqa: E402
from policies import AlwaysMax, AlwaysMin, Fixed, K8sHPA, StaticRamp, Threshold  # noqa: E402

SEEDS = tuple(range(1000, 1005))
RHOS = (0.3, 0.5, 0.7, 0.9, 1.1)
FRACS = (0.0, 0.005, 0.01, 0.02, 0.05, 0.10, 0.50)
VARIANTS = load_reward_dinos()[0]["variants"]
SEL = json.load(open(os.path.join(HERE, "selection_baselines_dinos.json")))["selected"]




def variant_env(variant, workload="W0", **kw):
    P = SimParams().with_(reward_mode="dinos")
    env = SimV2(P, workload=workload, **kw)
    env.dinos = {**env.dinos, **VARIANTS[variant]}
    return env


def substitution(variant):
    env = SimV2(SimParams().with_(reward_mode="dinos", init_pods=10, episode_steps=3), trace=[5000.0] * 3)
    env.reset(0)
    env.dinos = {**env.dinos, **VARIANTS[variant]}
    T, C = env.P.control_step_s, 10000.0
    res = {}
    for rho in RHOS:
        lam = rho * C
        arr = lam * T
        row = []
        for f in FRACS:
            env._mix = None
            failed = f * arr
            served = min(arr - failed, C * T)
            r, _ = env._dinos_reward(lam, served, failed, C, 10.0, T)
            row.append(r)
        res[rho] = row
    return res


def policies():
    P = SimParams()
    pols = [("always_min", AlwaysMin, ()), ("always_max", AlwaysMax, ())]
    pols += [("fixed", Fixed, (c,)) for c in range(P.min_pods, P.max_pods + 1)]
    pols += [("static_ramp", StaticRamp, (c,)) for c in range(P.min_pods, P.max_pods + 1)]
    pols += [("threshold", Threshold, tuple(SEL["threshold"])), ("k8s_hpa", K8sHPA, (SEL["k8s_hpa"],))]
    return pols


def replay(job):
    variant, name, cls, arg, seed = job
    env = variant_env(variant, **(K8sHPA.env_kwargs if name == "k8s_hpa" else {}))
    pol = cls(*arg)
    obs, _ = env.reset(seed, init_pods=getattr(pol, "init_pods", None))
    pol.reset()
    acc = dict(ret=0.0, r_L=0.0, r_D=0.0, r_N=0.0, r_U=0.0, r_M=0.0, failed=0.0, arrived=0.0)
    while True:
        obs, r, term, trunc, info = env.step(pol.act(obs))
        acc["ret"] += r
        for k in ("r_L", "r_D", "r_N", "r_U", "r_M"):
            acc[k] += info["dinos"][k]
        acc["failed"] += info["failed"]
        acc["arrived"] += info["arrived"]
        if term or trunc:
            break
    return variant, name, arg, seed, acc


def main():
    jobs = [(v, n, c, a, s) for v in VARIANTS for n, c, a in policies() for s in SEEDS]
    with mp.get_context("fork").Pool(int(os.environ.get("JOBS", 8))) as pool:
        out = pool.map(replay, jobs, chunksize=4)
    agg = {}
    for v, n, a, s, acc in out:
        agg.setdefault((v, n, a), []).append(acc)
    mean = {k: {m: float(np.mean([x[m] for x in L])) for m in L[0]} for k, L in agg.items()}
    md = ["# Reward-variant prototypes (dev seeds 1000-1004, deterministic baseline replays, no training)\n",
          "Generated by `reward_variants.py`. Variants (reward_dinos.json `variants`): **default** = p95 D, served-U; "
          "**V1** = mean latency of all requests of the step (failed at 60 s) / SLO; **V2** = V1 + U = min(100, "
          "100 lambda_offered / C); **V3** = p95 D + offered-U. Coefficients (3,-5,-10,-0.5,-0.5) unchanged.\n"]
    summary = {}
    for v in VARIANTS:
        md.append(f"\n## {v}: {VARIANTS[v]}\n")
        sub = substitution(v)
        md.append("### (1) Same-state substitution (10 pods, C=10000, billed 10; reward per step; columns = failed fraction "
                  f"{list(FRACS)}; rho 1.1: served capped at C*T, p95 uses existing 1e-3 clip)\n")
        md.append("| rho | " + " | ".join(f"{f:g}" for f in FRACS) + " | strictly decreasing | max drop (pair) | max rise |")
        md.append("|---|" + "---|" * (len(FRACS) + 3))
        mono_all, cliff = True, (0.0, None)
        for rho, row in sub.items():
            d = np.diff(row)
            mono = bool(np.all(d < 0))
            mono_all &= mono
            j = int(np.argmin(d))
            if -d[j] > cliff[0]:
                cliff = (-float(d[j]), (rho, FRACS[j], FRACS[j + 1]))
            md.append(f"| {rho} | " + " | ".join(f"{x:.1f}" for x in row) +
                      f" | {'yes' if mono else 'NO'} | {-d[j]:.1f} ({FRACS[j]:g}->{FRACS[j+1]:g}) | {max(d.max(), 0):.1f} |")
        md.append(f"\nVerdict: strictly decreasing everywhere = **{mono_all}**; cliff (max adjacent drop) = "
                  f"**{cliff[0]:.1f}** at (rho, f) = {cliff[1]}.\n")
        md.append("### (2) Replay, mean over 5 dev seeds (selected values from selection_baselines_dinos.json)\n")
        md.append("| policy | return | sum r_L | sum r_D | sum r_N | sum r_U | sum r_M | failed (req) | failed share |")
        md.append("|---|---|---|---|---|---|---|---|---|")
        rows = {}
        for (vv, n, a), m in mean.items():
            if vv != v:
                continue
            rows[(n, a)] = m
        fixed = {a[0]: m for (n, a), m in rows.items() if n == "fixed"}
        ramp = {a[0]: m for (n, a), m in rows.items() if n == "static_ramp"}
        bf = max(fixed, key=lambda c: fixed[c]["ret"])
        br = max(ramp, key=lambda c: ramp[c]["ret"])
        show = [("always_min", ()), ("always_max", ()), ("fixed", (bf,)), ("fixed", (SEL["fixed"],)),
                ("static_ramp", (br,)), ("static_ramp", (SEL["static_ramp"],)),
                ("threshold", tuple(SEL["threshold"])), ("k8s_hpa", (SEL["k8s_hpa"],))]
        for n, a in show:
            m = rows[(n, a)]
            tag = n + (f"({','.join(map(str, a))})" if a else "")
            if n in ("fixed", "static_ramp") and a[0] == SEL[n] and a[0] != (bf if n == "fixed" else br):
                tag += " [default-selected]"
            elif n in ("fixed", "static_ramp"):
                tag += " [best]"
            md.append(f"| {tag} | {m['ret']:.0f} | {m['r_L']:.0f} | {m['r_D']:.0f} | {m['r_N']:.0f} | {m['r_U']:.0f} | "
                      f"{m['r_M']:.0f} | {m['failed']:.0f} | {m['failed']/m['arrived']:.4f} |")
        md.append(f"\nBest fixed c = **{bf}** (return {fixed[bf]['ret']:.0f}); best static_ramp c = {br} "
                  f"({ramp[br]['ret']:.0f}); k8s_hpa({SEL['k8s_hpa']}) = {rows[('k8s_hpa',(SEL['k8s_hpa'],))]['ret']:.0f}. "
                  f"Fixed-c grid failed share (c=1..30): " +
                  ", ".join(f"{c}:{fixed[c]['failed']/fixed[c]['arrived']:.3f}" for c in sorted(fixed) if c <= 20) + "\n")
        summary[v] = dict(mono=mono_all, cliff=cliff, best_fixed=bf, best_fixed_ret=fixed[bf]["ret"],
                          hpa=rows[("k8s_hpa", (SEL["k8s_hpa"],))]["ret"])
    md.append("\n## Summary\n\n```\n" + json.dumps(summary, indent=1, default=str) + "\n```\n")
    open(os.path.join(HERE, "reward_variants_report.md"), "w").write("\n".join(md))
    print(json.dumps(summary, indent=1, default=str))


if __name__ == "__main__":
    main()
